// The A4 transcript. Copied from the original app; keep the layout in step with the JSON record.
import { parseMd, runs } from "../markdown/markdown";
import type { Entry, MeetingRecord } from "../meeting/types";
import { FRAME } from "../prompts/prompts";
import { ALL_SEATS, CHAIR } from "../prompts/roles";

// pdfmake document definitions are plain, loosely shaped objects.
type Node = Record<string, any>;

const PDF = { ink: "#16202b", muted: "#5a6876", line: "#d3dae1", sunk: "#f1f4f7", warn: "#fff4dc", warnInk: "#6b4a00" };
const colourFor = (roleId: string) => (ALL_SEATS.find((r) => r.id === roleId) || CHAIR).pdf;
function mdToPdf(md: string): Node[] {
  return parseMd(md).map((b) => b.t === "h" ? { text: b.text.toUpperCase(), style: "mh" }
    : b.t === "ul" ? { ul: b.items.map((i) => ({ text: runs(i) })), margin: [0, 0, 0, 6] }
    : { text: runs(b.text), margin: [0, 0, 0, 6] });
}
function speakerBlock(e: Entry, big?: boolean): Node {
  const colour = colourFor(e.roleId);
  const content = e.response ? mdToPdf(e.response)
    : [{ text: "No response" + (e.error ? " (" + e.error + ")" : "") + ".", italics: true, color: PDF.muted }];
  return {
    table: { widths: ["*"], body: [[{ stack: ([
      { columns: [{ text: e.role, bold: true, color: colour, fontSize: big ? 12 : 10.5 }, { text: e.provider + " · " + e.model, alignment: "right", style: "small" }], margin: [0, 0, 0, 6] },
    ] as Node[]).concat(content) }]] },
    layout: {
      hLineWidth: () => 0, vLineWidth: (i: number) => (i === 0 ? 3 : 0), vLineColor: () => colour,
      paddingLeft: () => 12, paddingRight: () => 4, paddingTop: () => 2, paddingBottom: () => 2,
    },
    margin: [0, 0, 0, 14],
  };
}
// The attached images as thumbnails, three to a row, followed by the radiologist's labelled report.
function imagesSection(rec: MeetingRecord, entry: Entry | undefined): Node[] {
  const images = rec.images!;
  const rows: Node[] = [];
  for (let i = 0; i < images.length; i += 3) {
    const row = images.slice(i, i + 3);
    rows.push({
      columns: [0, 1, 2].map((j) => row[j] ? { width: "*", stack: [
        { image: "data:" + row[j].mediaType + ";base64," + row[j].data, fit: [140, 140], margin: [0, 0, 0, 4] },
        { text: row[j].label + (row[j].caption ? ": " + row[j].caption : ""), style: "small" },
      ] } : { width: "*", text: "" }),
      columnGap: 12, margin: [0, 0, 0, 12], unbreakable: true,
    });
  }
  return [
    { text: "Images and imaging review", style: "h2", headlineLevel: 1 },
    { table: { widths: ["*"], body: [[{ text: [{ text: "AI image interpretation. Unvalidated, for research only. ", bold: true }, "The user confirmed each image had been checked for identifiers before it was used."], color: PDF.warnInk, fillColor: PDF.warn, margin: [8, 6, 8, 6] }]] }, layout: "noBorders", margin: [0, 0, 0, 10] },
    { text: rec.imagesSeenByAll
      ? "The radiologist reviewed these images before the meeting. Every consultant also saw them with their first opinion."
      : "The radiologist reviewed these images before the meeting. The other consultants read the report, not the images.", style: "note" },
    ...rows,
    entry ? speakerBlock(entry) : { text: "The meeting was stopped before the imaging review.", italics: true, color: PDF.muted, margin: [0, 0, 0, 14] },
  ];
}

export function buildPdf(rec: MeetingRecord): Node {
  const started = new Date(rec.startedAt);
  const when = started.toLocaleString("en-GB", { day: "numeric", month: "long", year: "numeric", hour: "2-digit", minute: "2-digit" });
  const chairRound = rec.rounds.find((r) => r.name === "Chair's decision");
  const chairEntry = chairRound && chairRound.entries[0];
  const imagingRound = rec.rounds.find((r) => r.name === "Imaging review");
  const discussion = rec.rounds.filter((r) => r !== chairRound && r !== imagingRound);
  const panelRows = rec.seats.map((s) => [{ text: s.role, color: colourFor(s.roleId), bold: true }, { text: s.provider + " · " + s.model, style: "small" }]);

  const content: Node[] = [
    { text: "MDT MEETING TRANSCRIPT", style: "eyebrow" },
    { text: rec.caseTitle || "Case discussion", style: "title" },
    { text: "Revision MDT Simulator · " + when, style: "sub" },
    { table: { widths: ["*"], body: [[{ text: [{ text: "Simulated meeting. ", bold: true }, "Generated by AI models for research purposes from a fictional or anonymised case. Not clinical advice."], color: PDF.warnInk, fillColor: PDF.warn, margin: [8, 6, 8, 6] }]] }, layout: "noBorders", margin: [0, 0, 0, 16] },
    { columns: [
      { width: "*", stack: [{ text: "PANEL", style: "label" }, { table: { widths: ["auto", "*"], body: panelRows }, layout: { hLineWidth: () => 0, vLineWidth: () => 0, paddingLeft: () => 0, paddingRight: () => 10, paddingTop: () => 2, paddingBottom: () => 2 } }] },
      { width: 150, stack: [
        { text: "DISCUSSION ROUNDS", style: "label" }, { text: String(rec.discussionRounds), margin: [0, 0, 0, 8] },
        ...(rec.images?.length ? [{ text: "IMAGES", style: "label" }, { text: rec.images.length + " attached", margin: [0, 0, 0, 8] }] : []),
        { text: "STATUS", style: "label" }, { text: rec.stoppedEarly ? "Stopped before completion" : "Complete" },
      ] },
    ], columnGap: 20, margin: [0, 0, 0, 18] },

    { text: "Outcome", style: "h2" },
    chairEntry ? speakerBlock(chairEntry, true) : { text: "The meeting was stopped before the chair recorded a decision.", italics: true, color: PDF.muted, margin: [0, 0, 0, 14] },

    { text: "Case summary", style: "h2" },
    { table: { widths: ["*"], body: [[{ text: rec.caseText, fontSize: 9.5, preserveLeadingSpaces: true, margin: [10, 8, 10, 8] }]] }, layout: { hLineWidth: () => 0, vLineWidth: () => 0, fillColor: () => PDF.sunk }, margin: [0, 0, 0, 18] },
  ];
  if (rec.images?.length) content.push(...imagesSection(rec, imagingRound?.entries[0]));
  discussion.forEach((rd, i) => {
    content.push({ text: rd.name, style: "h2", headlineLevel: 1 });
    content.push({ text: i === 0 ? "Each consultant read the case alone, without seeing anyone else's view." : "Each consultant had read all the other opinions and responded to them.", style: "note" });
    rd.entries.forEach((e) => content.push(speakerBlock(e)));
  });
  content.push({ text: "Appendix: instructions given to each seat", style: "h2", pageBreak: "before" });
  content.push({ text: "Every prompt began with the shared framing below, followed by the role description, the case, and the instructions for that round.", style: "note" });
  content.push({ text: FRAME, fontSize: 9, color: PDF.muted, margin: [0, 0, 0, 12] });
  rec.seats.forEach((s) => content.push({ stack: [{ text: s.role, bold: true, color: colourFor(s.roleId) }, { text: "You are " + s.brief, fontSize: 9.5 }], margin: [0, 0, 0, 10], unbreakable: true }));

  return {
    pageSize: "A4", pageMargins: [50, 56, 50, 56],
    info: { title: "MDT transcript: " + (rec.caseTitle || "case"), subject: "Revision MDT Simulator", creator: "Revision MDT Simulator" },
    header: (page: number) => page === 1 ? null : { columns: [{ text: "Revision MDT Simulator", style: "running" }, { text: rec.caseTitle || "", style: "running", alignment: "right" }], margin: [50, 26, 50, 0] },
    footer: (cur: number, total: number) => ({ columns: [{ text: "Simulated meeting · not clinical advice", style: "running" }, { text: "Page " + cur + " of " + total, style: "running", alignment: "right" }], margin: [50, 20, 50, 0] }),
    content,
    // keep a round heading with the first speaker below it
    pageBreakBefore: (node: Node, after: unknown[]) => node.headlineLevel === 1 && after.length < 6,
    defaultStyle: { font: "Roboto", fontSize: 10, lineHeight: 1.25, color: PDF.ink },
    styles: {
      eyebrow: { fontSize: 8.5, color: PDF.muted, characterSpacing: 1, margin: [0, 0, 0, 4] },
      title: { fontSize: 22, bold: true, margin: [0, 0, 0, 2] },
      sub: { fontSize: 10, color: PDF.muted, margin: [0, 0, 0, 14] },
      h2: { fontSize: 14, bold: true, margin: [0, 6, 0, 8] },
      label: { fontSize: 8, color: PDF.muted, characterSpacing: 0.8, margin: [0, 0, 0, 3] },
      mh: { fontSize: 8, bold: true, color: PDF.muted, characterSpacing: 0.6, margin: [0, 4, 0, 3] },
      note: { fontSize: 9.5, italics: true, color: PDF.muted, margin: [0, 0, 0, 10] },
      small: { fontSize: 8.5, color: PDF.muted },
      running: { fontSize: 8, color: PDF.muted },
    },
  };
}
