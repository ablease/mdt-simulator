// The meeting as a Word document, laid out like the PDF, so the researcher can edit it.
// The docx library is only loaded when someone asks for a Word file.
import { parseMd, runs } from "../markdown/markdown";
import { CHAIR_ROUND, IMAGING } from "../meeting/rounds";
import type { Entry, MeetingRecord } from "../meeting/types";
import { FRAME } from "../prompts/prompts";
import { fileStem, saveBlob } from "./download";
import { colourFor, PDF, researchRows } from "./pdfDocument";

const hex = (c: string) => c.replace("#", "").toUpperCase();
const bytes = (base64: string) => Uint8Array.from(atob(base64), (ch) => ch.charCodeAt(0));

export async function buildWord(rec: MeetingRecord): Promise<Blob> {
  const {
    AlignmentType, BorderStyle, Document, Footer, Header, HeadingLevel, ImageRun, Packer, PageNumber,
    Paragraph, ShadingType, Table, TableCell, TableRow, TextRun, WidthType,
  } = await import("docx");
  type Para = InstanceType<typeof Paragraph>;
  type Block = Para | InstanceType<typeof Table>;

  const muted = hex(PDF.muted);
  const text = (t: string, opts: { bold?: boolean; italics?: boolean; color?: string; size?: number } = {}) => new TextRun({ text: t, ...opts });
  const heading = (t: string) => new Paragraph({ text: t, heading: HeadingLevel.HEADING_2, spacing: { before: 240, after: 120 }, keepNext: true });
  const note = (t: string) => new Paragraph({ children: [text(t, { italics: true, color: muted, size: 19 })], spacing: { after: 160 } });
  const box = (children: InstanceType<typeof TextRun>[]) => new Paragraph({
    children, shading: { type: ShadingType.CLEAR, fill: hex(PDF.warn), color: "auto" }, spacing: { after: 240 },
    border: { top: { style: BorderStyle.SINGLE, size: 1, color: hex(PDF.warn), space: 4 }, bottom: { style: BorderStyle.SINGLE, size: 1, color: hex(PDF.warn), space: 4 } },
  });

  const markdown = (md: string, bar: object): Para[] => parseMd(md).flatMap((b) => {
    if (b.t === "h") return [new Paragraph({ children: [text(b.text.toUpperCase(), { bold: true, color: muted, size: 16 })], border: bar, spacing: { before: 120, after: 40 }, keepNext: true })];
    if (b.t === "ul") return b.items.map((item) => new Paragraph({ children: runs(item).map((r) => text(r.text, { bold: r.bold })), bullet: { level: 0 }, border: bar }));
    return [new Paragraph({ children: runs(b.text).map((r) => text(r.text, { bold: r.bold })), border: bar, spacing: { after: 80 } })];
  });

  // One seat's answer, with a bar in the seat's colour down the left, as in the PDF.
  const speaker = (e: Entry, big = false): Para[] => {
    const colour = hex(colourFor(e.roleId));
    const bar = { left: { style: BorderStyle.SINGLE, size: 18, color: colour, space: 10 } };
    return [
      new Paragraph({ children: [text(e.role, { bold: true, color: colour, size: big ? 24 : 21 }), text("   " + e.provider + " · " + e.model, { color: muted, size: 17 })], border: bar, keepNext: true, spacing: { before: 120, after: 80 } }),
      ...(e.response ? markdown(e.response, bar) : [new Paragraph({ children: [text("No response" + (e.error ? " (" + e.error + ")" : "") + ".", { italics: true, color: muted })], border: bar })]),
      new Paragraph({ text: "", spacing: { after: 120 } }),
    ];
  };

  const table = (rows: [string, string][], firstColour?: (i: number) => string) => new Table({
    width: { size: 100, type: WidthType.PERCENTAGE },
    rows: rows.map(([k, v], i) => new TableRow({ children: [
      new TableCell({ width: { size: 30, type: WidthType.PERCENTAGE }, children: [new Paragraph({ children: [text(k, { bold: true, color: firstColour?.(i) })] })] }),
      new TableCell({ children: v.split("\n").map((line) => new Paragraph({ text: line })) }),
    ] })),
  });

  const started = new Date(rec.startedAt).toLocaleString("en-GB", { day: "numeric", month: "long", year: "numeric", hour: "2-digit", minute: "2-digit" });
  const chairRound = rec.rounds.find((r) => r.name === CHAIR_ROUND);
  const imagingRound = rec.rounds.find((r) => r.name === IMAGING);
  const research = researchRows(rec.research);

  const body: Block[] = [
    new Paragraph({ children: [text("MDT MEETING TRANSCRIPT", { color: muted, size: 17 })] }),
    new Paragraph({ text: rec.caseTitle || "Case discussion", heading: HeadingLevel.TITLE }),
    new Paragraph({ children: [text("Revision MDT Simulator · " + started, { color: muted })], spacing: { after: 200 } }),
    box([text("Simulated meeting. ", { bold: true, color: hex(PDF.warnInk) }), text("Generated by AI models for research purposes from a fictional or anonymised case. Not clinical advice.", { color: hex(PDF.warnInk) })]),
    heading("Panel"),
    table(rec.seats.map((s) => [s.role, s.provider + " · " + s.model]), (i) => hex(colourFor(rec.seats[i].roleId))),
    new Paragraph({ text: `${rec.discussionRounds === 1 ? "1 round" : rec.discussionRounds + " rounds"} of discussion. ${rec.images?.length ? rec.images.length + (rec.images.length === 1 ? " image" : " images") + " attached. " : ""}${rec.stoppedEarly ? "Stopped before completion." : "Complete."}`, spacing: { before: 120 } }),
    heading("Outcome"),
    ...(chairRound?.entries[0] ? speaker(chairRound.entries[0], true) : [note("The meeting was stopped before the chair recorded a decision.")]),
  ];
  if (research.length) body.push(heading("Research notes"), note("Added by the researcher after the meeting. The AI did not see these."), table(research));
  body.push(heading("Case summary"), ...rec.caseText.split("\n").map((line) => new Paragraph({ text: line })));

  if (rec.images?.length) {
    body.push(
      heading("Images and imaging review"),
      box([text("AI image interpretation. Unvalidated, for research only. ", { bold: true, color: hex(PDF.warnInk) }), text("The user confirmed each image had been checked for identifiers before it was used.", { color: hex(PDF.warnInk) })]),
      note(rec.imagesSeenByAll
        ? "The radiologist reviewed these images before the meeting. Every consultant also saw them with their first opinion."
        : "The radiologist reviewed these images before the meeting. The other consultants read the report, not the images."),
    );
    for (const img of rec.images) {
      const scale = Math.min(1, 220 / Math.max(img.width, img.height));
      const label = img.label + (img.caption ? ": " + img.caption : "");
      body.push(
        new Paragraph({ children: [new ImageRun({ type: "jpg", data: bytes(img.data), transformation: { width: Math.round(img.width * scale), height: Math.round(img.height * scale) }, altText: { name: img.label, title: label, description: label } })], keepNext: true }),
        new Paragraph({ children: [text(label, { color: muted, size: 17 })], spacing: { after: 160 } }),
      );
    }
    body.push(...(imagingRound?.entries[0] ? speaker(imagingRound.entries[0]) : [note("The meeting was stopped before the imaging review.")]));
  }

  rec.rounds.filter((r) => r !== chairRound && r !== imagingRound).forEach((round, i) => {
    body.push(heading(round.name), note(i === 0 ? "Each consultant read the case alone, without seeing anyone else's view." : "Each consultant had read all the other opinions and responded to them."));
    round.entries.forEach((e) => body.push(...speaker(e)));
  });

  body.push(
    new Paragraph({ text: "Appendix: instructions given to each seat", heading: HeadingLevel.HEADING_2, pageBreakBefore: true }),
    note("Every prompt began with the shared framing below, followed by the role description, the case, and the instructions for that round."),
    new Paragraph({ children: [text(FRAME, { color: muted, size: 18 })], spacing: { after: 200 } }),
    ...rec.seats.flatMap((s) => [
      new Paragraph({ children: [text(s.role, { bold: true, color: hex(colourFor(s.roleId)) })], keepNext: true }),
      new Paragraph({ children: [text("You are " + s.brief, { size: 19 })], spacing: { after: 160 } }),
    ]),
  );

  const doc = new Document({
    creator: "Revision MDT Simulator",
    title: "MDT transcript: " + (rec.caseTitle || "case"),
    description: "Simulated meeting. AI-generated, for research only. Not clinical advice.",
    styles: { default: { document: { run: { font: "Arial", size: 20, color: hex(PDF.ink) } } } },
    sections: [{
      properties: { page: { margin: { top: 1000, bottom: 1000, left: 1000, right: 1000 } } },
      headers: { default: new Header({ children: [new Paragraph({ children: [text("Revision MDT Simulator · " + (rec.caseTitle || ""), { color: muted, size: 16 })], alignment: AlignmentType.RIGHT })] }) },
      footers: { default: new Footer({ children: [new Paragraph({ children: [
        text("Simulated meeting · not clinical advice · ", { color: muted, size: 16 }),
        new TextRun({ children: ["Page ", PageNumber.CURRENT, " of ", PageNumber.TOTAL_PAGES], color: muted, size: 16 }),
      ] })] }) },
      children: body,
    }],
  });
  return Packer.toBlob(doc);
}

export async function downloadWord(rec: MeetingRecord) {
  saveBlob(await buildWord(rec), fileStem(rec) + ".docx");
}
