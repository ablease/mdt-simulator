// A report across several saved meetings, such as the same case run five times: a summary table with
// one row per run, then each run's chair decision in turn.
import { chairAnswer, ratingLabel, shortWhen as when, summarise } from "../meeting/summary";
import { CHAIR_ROUND } from "../meeting/rounds";
import type { SavedRecord } from "../meeting/types";
import { PAGE, PDF, researchRows, speakerBlock } from "./pdfDocument";

type Node = Record<string, any>;

const caseLabel = (r: SavedRecord) => (r.research.caseTag ? r.research.caseTag + ": " : "") + (r.caseTitle || "Case discussion");

export function buildComparison(recs: SavedRecord[], now = new Date()): Node {
  const head = ["Run", "Date", "Case", "Panel models", "Decision", "Agreement", "Actual MDT decision", "Rating"]
    .map((text) => ({ text, bold: true, fontSize: 8, color: PDF.muted }));
  const rows = recs.map((r, i) => {
    const s = summarise(r, "");
    return [String(i + 1), when(r.startedAt), caseLabel(r), s.panel, s.outcome || "No decision recorded", s.agreement || "Not stated", r.research.actualDecision, ratingLabel(r.research.rating)]
      .map((text) => ({ text, fontSize: 8.5 }));
  });

  const content: Node[] = [
    { text: "COMPARISON REPORT", style: "eyebrow" },
    { text: recs.length === 1 ? "1 simulated meeting" : recs.length + " simulated meetings", style: "title" },
    { text: "Revision MDT Simulator · produced " + when(now.toISOString()), style: "sub" },
    { table: { widths: ["*"], body: [[{ text: [{ text: "Simulated meetings. ", bold: true }, "Every decision here was generated by AI models for research purposes from fictional or anonymised cases. Not clinical advice."], color: PDF.warnInk, fillColor: PDF.warn, margin: [8, 6, 8, 6] }]] }, layout: "noBorders", margin: [0, 0, 0, 16] },
    { text: "Summary", style: "h2" },
    { text: "Decision is the first line of the chair's decision. Actual MDT decision and rating were added by the researcher; the AI did not see them.", style: "note" },
    {
      table: { headerRows: 1, dontBreakRows: true, widths: [22, 58, 80, 110, "*", 52, "*", 46], body: [head, ...rows] },
      layout: { hLineWidth: (i: number) => (i === 1 ? 0.8 : 0.4), vLineWidth: () => 0, hLineColor: () => PDF.line, paddingTop: () => 4, paddingBottom: () => 4 },
      margin: [0, 0, 0, 18],
    },
  ];

  recs.forEach((r, i) => {
    const chair = r.rounds.find((rd) => rd.name === CHAIR_ROUND)?.entries[0];
    const research = researchRows(r.research).filter(([k]) => k !== "Case ID");
    content.push(
      { text: `Run ${i + 1}: ${caseLabel(r)}`, style: "h2", headlineLevel: 1, ...(i === 0 ? { pageBreak: "before" } : {}) },
      { text: when(r.startedAt) + " · " + summarise(r, "").panel + (r.stoppedEarly ? " · stopped before completion" : ""), style: "note" },
      chair && chairAnswer(r) ? speakerBlock(chair, true) : { text: "The chair didn't record a decision in this meeting.", italics: true, color: PDF.muted, margin: [0, 0, 0, 14] },
    );
    if (research.length) content.push({
      unbreakable: true,
      table: { widths: [110, "*"], body: research.map(([k, v]) => [{ text: k, bold: true, fontSize: 9 }, { text: v, fontSize: 9 }]) },
      layout: { hLineWidth: (j: number) => (j === 0 ? 0 : 0.5), vLineWidth: () => 0, hLineColor: () => PDF.line, paddingTop: () => 3, paddingBottom: () => 3 },
      margin: [0, 0, 0, 18],
    });
  });

  return {
    ...PAGE,
    pageSize: "A4", pageOrientation: "landscape", pageMargins: [44, 50, 44, 50],
    info: { title: "MDT comparison report", subject: "Revision MDT Simulator", creator: "Revision MDT Simulator" },
    header: (page: number) => page === 1 ? null : { columns: [{ text: "Revision MDT Simulator", style: "running" }, { text: "Comparison report", style: "running", alignment: "right" }], margin: [44, 22, 44, 0] },
    footer: (cur: number, total: number) => ({ columns: [{ text: "Simulated meetings · not clinical advice", style: "running" }, { text: "Page " + cur + " of " + total, style: "running", alignment: "right" }], margin: [44, 18, 44, 0] }),
    content,
  };
}
